        "💭 思考过程" to "💭 Ход рассуждений",
    )

    private fun translateDynamic(value: String): String? {
        return when {
            value.startsWith("版本 ") ->
                "Версия " + value.removePrefix("版本 ")
            value.startsWith("已启用 ") && value.endsWith(" 个工具") ->
                "Включено инструментов: " + value.removePrefix("已启用 ").removeSuffix(" 个工具")
            else -> null
        }
    }


    fun setLanguage(code: String) {
        languageCode = code
    }

    fun text(value: String): String {
        if (!languageCode.equals("ru", ignoreCase = true) &&
            !languageCode.startsWith("ru-", ignoreCase = true)
        ) {
            return value
        }
        russianTranslations[value]?.let { return it }
        translateDynamic(value)?.let { return it }
        return value
    }
